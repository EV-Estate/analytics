//! The embed's five catalogues, and the translation policy applied to them.
//!
//! Target-agnostic on purpose: `src/lib.rs` is wasm-only, but the snapshot
//! example and the catalogue test need the same resolution, so they pull this in
//! by `#[path]` the way they already do for `view`.
//!
//! `messages/en/common.json` is **generated** — `cargo run --example
//! dump_messages` — because English is authored at the `t!` sites in `view.rs`.
//! The other four are authored in the `{en, t}` envelope, byte-identical in
//! format to the conductor's, which is the point of a shared policy module.

use std::collections::BTreeMap;

use ev_lib::i18n::{
	Locale, Messages,
	policy::{TranslatedCatalogue, TranslatedEntry, resolve_catalogue},
};

const EN: &str = include_str!("../messages/en/common.json");
const RU: &str = include_str!("../messages/ru/common.json");
const VI: &str = include_str!("../messages/vi/common.json");
const FR: &str = include_str!("../messages/fr/common.json");
const DE: &str = include_str!("../messages/de/common.json");

/// The exact bytes `messages/en/common.json` is written as, so
/// `examples/dump_messages.rs` and the test that checks it cannot disagree about
/// formatting. Two-space indent and a trailing newline — `JSON.stringify(v, null,
/// 2)`, the shape the conductor's catalogues already have.
pub fn serialise(catalogue: &Messages) -> String {
	format!("{}\n", serde_json::to_string_pretty(catalogue).expect("a string map always serialises"))
}

/// The English catalogue as committed — the canonical key set.
pub fn source() -> Messages {
	serde_json::from_str(EN).expect("messages/en/common.json is generated by `cargo run --example dump_messages`")
}

/// The catalogue `locale` renders from, with rules 1.1/1.2 already applied: a
/// drifted or missing translation is English, never a hole.
///
/// This is the `fn(Locale) -> Messages` the `mfe!` macro takes, so the live
/// bundle and the static snapshot resolve through exactly the same path.
pub fn catalogue(locale: Locale) -> Messages {
	let en = source();
	match locale {
		Locale::En => en,
		_ => resolve_catalogue(locale, &en, &authored(locale)).messages,
	}
}

/// One translated catalogue, parsed out of its `{en, t}` envelope.
///
/// Hand-walked rather than derived: `ev_lib`'s `i18n` is zero-dep, so
/// `TranslatedEntry` carries no serde impls, and adding them to the framework to
/// save nine lines here would put a dependency in every consumer's wasm bundle.
pub fn authored(locale: Locale) -> TranslatedCatalogue {
	let json = match locale {
		Locale::En => EN,
		Locale::Ru => RU,
		Locale::Vi => VI,
		Locale::Fr => FR,
		Locale::De => DE,
	};
	let parsed: BTreeMap<String, BTreeMap<String, String>> = serde_json::from_str(json).unwrap_or_else(|e| panic!("messages/{locale}/common.json: {e}"));
	parsed
		.into_iter()
		.map(|(key, entry)| {
			let mut field = |name: &str| entry.get(name).unwrap_or_else(|| panic!("messages/{locale}/common.json: {key:?} has no {name:?} field")).clone();
			let parsed = TranslatedEntry { en: field("en"), t: field("t") };
			(key, parsed)
		})
		.collect()
}
